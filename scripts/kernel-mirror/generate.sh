#!/usr/bin/env bash
# Generates a throwaway SwiftPM package that mirrors the pure render-kernel sources and their
# Swift Testing suites (#364, #64). See README.md for what it proves and what it does not.
#
# Usage: scripts/kernel-mirror/generate.sh <empty directory outside the repository>
#
# Files listed in manifest.txt are byte-copied (each verified with cmp). Sources keep their
# repo-relative layout under Sources/FluxKlang/; tests go flat into Tests/FluxKlangTests/.
# Nothing is written inside the repository. Bash 3.2-compatible (macOS /bin/bash).
set -euo pipefail

die() { echo "kernel-mirror: error: $*" >&2; exit 1; }

script_dir=$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
repo=$(CDPATH='' cd -- "$script_dir/../.." && pwd -P)
manifest="$script_dir/manifest.txt"

[ "$#" -eq 1 ] || die "usage: $0 <empty destination directory outside the repository>"
case $1 in /*) ;; *) die "destination must be an absolute path: $1" ;; esac
[ ! -L "$1" ] || die "destination must not be a symlink: $1"
[ -d "$1" ] || die "destination must be an existing directory: $1"
[ -O "$1" ] || die "destination must be owned by the current user: $1"
dest=$(CDPATH='' cd -- "$1" && pwd -P)
[ "$dest" != / ] || die "destination must not be /"
case "$dest/" in "$repo/"*) die "destination is inside the repository: $dest" ;; esac
case "$repo/" in "$dest/"*) die "destination contains the repository: $dest" ;; esac
[ -z "$(ls -A -- "$dest")" ] || die "destination is not empty: $dest"
[ -f "$manifest" ] || die "manifest missing: $manifest"

trees=() excludes=() sources=() tests=()
line_no=0
while IFS= read -r line || [ -n "$line" ]; do
  line_no=$((line_no + 1))
  case $line in '' | '#'*) continue ;; esac
  read -r kind path extra <<< "$line" || true
  [ -n "${path:-}" ] && [ -z "${extra:-}" ] || die "manifest.txt:$line_no: expected '<kind> <path>': $line"
  case $path in /* | *..* | *'*'* | *'?'*) die "manifest.txt:$line_no: path must be repo-relative and literal: $path" ;; esac
  case $kind in
    tree) trees+=("$path") ;;
    exclude) excludes+=("$path") ;;
    source) sources+=("$path") ;;
    test) tests+=("$path") ;;
    *) die "manifest.txt:$line_no: unknown kind '$kind'" ;;
  esac
done < "$manifest"
[ "${#trees[@]}" -gt 0 ] && [ "${#tests[@]}" -gt 0 ] || die "manifest has no tree or no test entries"

contains() { # contains <needle> <items...>
  local needle=$1 item; shift
  for item in "$@"; do [ "$item" = "$needle" ] && return 0; done
  return 1
}

copy() { # copy <repo-relative source> <package-relative destination>
  local src="$repo/$1" dst="$dest/$2"
  [ -f "$src" ] && [ ! -L "$src" ] || die "manifest entry missing or not a regular file: $1"
  [ ! -e "$dst" ] || die "two entries map to $2"
  mkdir -p -- "$(dirname -- "$dst")"
  cp -- "$src" "$dst"
  cmp -s "$src" "$dst" || die "copy differs from source: $1"
}

source_count=0 test_count=0 excluded_seen=0
for tree in "${trees[@]}"; do
  [ -d "$repo/$tree" ] && [ ! -L "$repo/$tree" ] || die "manifest tree missing: $tree"
  listing=$(cd "$repo" && find "$tree" ! -type d | LC_ALL=C sort)
  [ -n "$listing" ] || die "manifest tree is empty: $tree"
  while IFS= read -r file; do
    if contains "$file" ${excludes[@]+"${excludes[@]}"}; then excluded_seen=$((excluded_seen + 1)); continue; fi
    case $file in
      *.swift) ;;
      .DS_Store | */.DS_Store) continue ;; # Finder metadata, never mirrored
      *) die "unreviewed non-Swift file in $tree: $file" ;;
    esac
    copy "$file" "Sources/FluxKlang/$file"
    source_count=$((source_count + 1))
  done <<< "$listing"
done
# Every exclude must name an existing file that a tree actually contained.
[ "$excluded_seen" -eq "${#excludes[@]}" ] || die "an exclude entry matches no file in any tree (stale manifest)"
for file in ${sources[@]+"${sources[@]}"}; do
  copy "$file" "Sources/FluxKlang/$file"
  source_count=$((source_count + 1))
done
for file in "${tests[@]}"; do
  copy "$file" "Tests/FluxKlangTests/$(basename -- "$file")"
  test_count=$((test_count + 1))
done

# A new RealtimeHandoffTests or KernelRetirementCarryTests file must be reviewed into the manifest,
# not silently skipped.
for path in "$repo"/FluxKlangTests/RealtimeHandoffTests*.swift "$repo"/FluxKlangTests/KernelRetirementCarryTests*.swift; do
  [ -e "$path" ] || die "no file matches $path"
  file=${path#"$repo/"}
  contains "$file" "${tests[@]}" || die "$file is not in manifest.txt; add it as a test entry"
done
[ -f "$dest/Sources/FluxKlang/Shared/Audio/Kernel/Events/KernelCycle.swift" ] \
  || die "the source-scan tests need Sources/FluxKlang/Shared/Audio/Kernel/Events/KernelCycle.swift"

# Tools 6.4 is Xcode 27's Swift (hosted: Xcode 27.1); .v27 matches project.yml's macOS 27.0 deployment target.
cat > "$dest/Package.swift" <<'SWIFT'
// swift-tools-version: 6.4
// Generated by scripts/kernel-mirror/generate.sh: a throwaway mirror, never committed.
import PackageDescription

let package = Package(
    name: "FluxKlangKernelMirror",
    platforms: [.macOS(.v27)],
    targets: [
        // Named FluxKlang so the copied tests' `@testable import FluxKlang` resolves unchanged.
        .target(name: "FluxKlang", path: "Sources/FluxKlang"),
        .testTarget(name: "FluxKlangTests", dependencies: ["FluxKlang"], path: "Tests/FluxKlangTests"),
    ],
    swiftLanguageModes: [.v6]
)
SWIFT

echo "kernel-mirror: $source_count source files, $test_count test files (cmp-verified) -> $dest"
