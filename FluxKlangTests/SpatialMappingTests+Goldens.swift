/// One legacy placement and its captured gains, one row per channel (mono: one
/// row; stereo: left then right), aligned with the layout's speakers.
struct SpatialMappingGoldenCase: Sendable {
    let legacyX: Double
    let legacyY: Double
    /// `nil` for a mono source.
    let width: Double?
    let gains: [[Double]]

    init(_ legacyX: Double, _ legacyY: Double, _ gains: [Double]) {
        self.legacyX = legacyX
        self.legacyY = legacyY
        self.width = nil
        self.gains = [gains]
    }

    init(_ legacyX: Double, _ legacyY: Double, width: Double, _ gains: [[Double]]) {
        self.legacyX = legacyX
        self.legacyY = legacyY
        self.width = width
        self.gains = gains
    }
}

